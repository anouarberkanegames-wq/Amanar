// Retourne le nombre de séances déjà incluses dans le package/durée en cours
function getIncludedCount(actId) {
  if (!bkState.pkg || !bkState.dureeKey) return 0;
  const p = bkState.pkg, d = bkState.dureeKey;
  const map = {
    1: { well: { semaine:2, long:3, long_plus:'∞' }, surf: { semaine:2, long:3, long_plus:'∞' } },
    2: { well: { souffler_sem:1, souffler_we:1, semaine:2, long:3, long_plus:4 } },
    3: { well: { souffler_sem:1, souffler_we:1, semaine:2, long:3, long_plus:4 } },
    4: { well: { semaine:1, long:1, long_plus:2 } },
    5: { well: { souffler_sem:1, souffler_we:1, semaine:1, long:2, long_plus:2 } },
    26:{ surf:{ semaine:1,long:1,long_plus:2 }, well:{ semaine:1,long:1,long_plus:2 }, nomad:{ semaine:1,long:1,long_plus:2 } }
  };
  const r = (map[actId]||{})[p];
  return r ? (r[d]||0) : 0;
}

function changeQty(id, delta) {
  const current = actsQty[id] || 0;
  const next = Math.max(0, current + delta);
  if (next === 0) delete actsQty[id];
  else actsQty[id] = next;
  renderTop3(); renderActs(); updateActRecap(); updatePrixFinal();
}

function toggleAct(id) {
  if (actsQty[id]) delete actsQty[id];
  else actsQty[id] = 1;
  renderTop3(); renderActs(); updateActRecap(); updatePrixFinal();
}

function updateActRecap() {
  const recap = document.getElementById('act-recap');
  const ids   = Object.keys(actsQty).map(Number);
  const sel   = ACTIVITES.filter(a=>ids.includes(a.id));
  if (!sel.length) { recap.classList.remove('show'); return; }
  const tot = sel.reduce((s,a) => s + a.prix*(actsQty[a.id]||1), 0);
  document.getElementById('act-recap-lines').innerHTML = sel.map(a=>{
    const q = actsQty[a.id]||1;
    const label = q > 1 ? `${a.icon} ${a.titre} ×${q}` : `${a.icon} ${a.titre}`;
    const price = a.prix===0 ? 'Gratuit' : (a.prix*q)+'€';
    return `<div class="act-recap-line"><span>${label}</span><span>${price}</span></div>`;
  }).join('');
  document.getElementById('act-recap-total').textContent = tot+'€';
  recap.classList.add('show');
}


