let _sbUrl = '', _sbKey = '', _sbReady = false;
function initBedCheckerSupabase(url, key) {
  _sbUrl = url; _sbKey = key; _sbReady = !!(url && key);
}

// Vérifier lits occupés via Supabase
async function getOccupiedBeds(arrive, depart) {
  if (!_sbReady || !arrive || !depart) return [];
  try {
    const resp = await fetch(
      `${_sbUrl}/rest/v1/reservations?select=lit,chambre&date_arrive=lt.${depart}&date_depart=gt.${arrive}&statut=neq.blocked`,
      { headers: { apikey: _sbKey, Authorization: `Bearer ${_sbKey}` } }
    );
    if (!resp.ok) return [];
    const data = await resp.json();
    return data.map(r => r.lit).filter(Boolean);
  } catch(e) { return []; }
}

