function renderCalendar() {
  const container = document.getElementById('rooms-container');
  const daysInMonth = new Date(currentYear, currentMonth+1, 0).getDate();
  const today = new Date();
  const todayStr = today.toISOString().split('T')[0];

  // Month label
  document.getElementById('cal-month-label').textContent =
    new Date(currentYear, currentMonth).toLocaleDateString('fr-FR',{month:'long',year:'numeric'})
    .replace(/^\w/,c=>c.toUpperCase());

  // Build days array
  const days = Array.from({length:daysInMonth},(_,i)=>{
    const d = new Date(currentYear, currentMonth, i+1);
    return {
      n: i+1,
      str: d.toISOString().split('T')[0],
      dow: d.getDay(),
      isWeekend: d.getDay()===0||d.getDay()===6,
      isToday: d.toISOString().split('T')[0]===todayStr,
      isPast: d < today && d.toISOString().split('T')[0]!==todayStr
    };
  });

  let html = '';

  // Header row
  html += '<div class="room-section"><div class="cal-grid-wrap"><div class="cal-grid">';
  html += '<div class="cal-header-row">';
  html += '<div class="cal-header-cell">Chambre / Lit</div>';
  days.forEach(d=>{
    const cls = [d.isWeekend?'weekend':'',d.isToday?'today':''].filter(Boolean).join(' ');
    html += `<div class="cal-header-cell ${cls}">${d.n}<br><span style="font-size:0.55rem">${['Di','Lu','Ma','Me','Je','Ve','Sa'][d.dow]}</span></div>`;
  });
  html += '</div>';

  // Rooms
  Object.entries(ROOMS).forEach(([room, beds])=>{
    const isSuite = room==='Suite';
    html += `<div style="background:var(--w2);padding:0.4rem 1rem;font-size:0.75rem;font-weight:700;color:var(--c2);letter-spacing:0.08em;border-bottom:1px solid var(--w3)">${ROOM_ICONS[room]}</div>`;

    beds.forEach(bed=>{
      html += '<div class="cal-row">';
      const bedLbl = (typeof BED_LABELS !== 'undefined' && BED_LABELS[bed]) ? BED_LABELS[bed] : bed;
      html += `<div class="row-label cal-cell ${isSuite?'row-label-suite':''}">${bedLbl}</div>`;

      days.forEach(d=>{
        const cls = [d.isWeekend?'weekend':'',d.isToday?'today':'',d.isPast?'past':''].filter(Boolean).join(' ');
        // Find reservation for this bed and day
        const resa = reservations.find(r=>
          r.chambre===room && r.lit===bed &&
          r.date_arrive <= d.str && r.date_depart > d.str
        );
        let chipHtml = '';
        if(resa) {
          const color = resa.statut==='blocked' ? 'var(--gray)'
            : resa.statut==='checkout' ? 'var(--green)'
            : resa.statut==='pending' ? 'var(--blue)'
            : PKG_COLORS[resa.package]||'var(--t1)';
          const isFirst = resa.date_arrive===d.str;
          const label = isFirst ? (resa.prenom||'').slice(0,10) + (resa.package?` · ${resa.package}`:'') : '';
          chipHtml = `<div class="chip" style="background:${color}" onclick="editResa('${resa.id}')" title="${resa.prenom} ${resa.nom} · ${resa.date_arrive}→${resa.date_depart}">${label}</div>`;
        }
        html += `<div class="cal-cell ${cls}" onclick="${resa?'':`quickAdd('${room}','${bed}','${d.str}')`}">${chipHtml}</div>`;
      });
      html += '</div>';
    });
  });

  html += '</div></div></div>';
  container.innerHTML = html;
}

