function selectBed(bed, isOccupied) {
  if (isOccupied) return;
  selectedBed = bed;
  const info = document.getElementById('bed-selected-info');

  // Reset all buttons
  document.querySelectorAll('[id^="bed-btn-"]').forEach(btn => {
    btn.style.background = btn.id === 'bed-btn-any' ? 'rgba(196,82,26,0.06)' : '#fff';
    btn.style.borderColor = btn.id === 'bed-btn-any' ? 'var(--t1)' : 'var(--w3)';
    btn.style.transform = 'scale(1)';
  });

  // Highlight selected
  const target = document.getElementById('bed-btn-' + (bed || 'any'));
  if (target) {
    target.style.background = 'var(--t1)';
    target.style.borderColor = 'var(--t1)';
    target.style.color = '#fff';
    target.style.transform = 'scale(1.08)';
    // Fix child text colors
    target.querySelectorAll('span').forEach(s => s.style.color = '#fff');
  }

  if (info) {
    if (bed) {
      const d = (typeof BED_DETAILS !== 'undefined' && BED_DETAILS[bed]);
      const name = d ? d.name : bed;
      const tip  = d ? ' — ' + d.tip : '';
      info.textContent = `✅ ${name} sélectionné · ${d ? d.size : '90×200cm'}${tip}`;
    } else {
      info.textContent = (currentLang==='en'?"✨ No preference — we'll pick the best available bed for you at check-in.":"✨ Pas de préférence — on choisira le meilleur lit disponible pour vous à l'arrivée.");
    }
  }
}

