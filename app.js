function bkUpdateSteps() {
  const hasDates  = bkState.nuits > 0;
  const hasPkg    = !!bkState.pkg;
  const hasOpts   = hasPkg && !bkState.isSpecial && bkState.dureeKey;
  const hasPrix   = hasOpts;
  const hasPaymt  = hasPrix;

  const steps = [
    {c:'sc1',l:'sl1',done:hasDates,        active:!hasDates},
    {c:'sc2',l:'sl2',done:hasPkg&&hasDates,active:hasDates&&!hasPkg},
    {c:'sc3',l:'sl3',done:hasOpts,         active:hasPkg&&!hasOpts&&!bkState.isSpecial},
    {c:'sc4',l:'sl4',done:false,           active:hasOpts},
    {c:'sc5',l:'sl5',done:false,           active:hasPaymt},
  ];
  const lines = ['sline1','sline2','sline3','sline4'];

  steps.forEach((s,i) => {
    const c = document.getElementById(s.c);
    const l = document.getElementById(s.l);
    if (!c) return;
    c.classList.remove('active','done');
    l.classList.remove('active','done');
    if (s.done)        { c.classList.add('done'); l.classList.add('done'); }
    else if (s.active) { c.classList.add('active'); l.classList.add('active'); }
    if (lines[i]) document.getElementById(lines[i]).classList.toggle('done', s.done||false);
  });
}

