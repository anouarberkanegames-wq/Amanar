function getBkEl(id){ return document.getElementById(id); }
function onDateChange(evt) {
  try {
    const checkinEl = getBkEl('checkin');
    const checkoutEl = getBkEl('checkout');
    const pill = getBkEl('nuits-pill');
    const icon = getBkEl('nuits-icon');
    const txt  = getBkEl('nuits-txt');
    if (!checkinEl || !checkoutEl || !pill || !icon || !txt) return;

    const cin  = (checkinEl.value || '').trim();
    const cout = (checkoutEl.value || '').trim();

    if (cin) {
      const d1 = new Date(cin + 'T00:00:00');
      if (!Number.isNaN(d1.getTime())) {
        const minOut = new Date(d1);
        minOut.setDate(minOut.getDate() + 1);
        const minOutStr = minOut.toISOString().split('T')[0];
        checkoutEl.min = minOutStr;
        if (checkoutEl.value && checkoutEl.value < minOutStr) checkoutEl.value = '';
      }
    }

    if (!cin || !cout) {
      pill.style.display='none';
      bkState.nuits=0;
      bkState.dureeKey=null;
      hideAllFlows();
      return;
    }

    const d1 = new Date(cin + 'T00:00:00');
    const d2 = new Date(cout + 'T00:00:00');
    if (Number.isNaN(d1.getTime()) || Number.isNaN(d2.getTime())) {
      pill.className='nuits-pill invalid'; pill.style.display='flex';
      icon.textContent='✗'; txt.textContent='Dates invalides';
      hideAllFlows();
      return;
    }

    const diff = Math.round((d2 - d1) / 86400000);
    if (diff <= 0) {
      pill.className='nuits-pill invalid'; pill.style.display='flex';
      icon.textContent='✗'; txt.textContent='Date de départ invalide';
      hideAllFlows();
      return;
    }

    bkState.nuits = diff;

    if (diff===3) {
      const day = d1.getDay();
      bkState.dureeKey = (day===5||day===6||day===0) ? 'souffler_we' : 'souffler_sem';
      const lbl = (day===5||day===6||day===0) ? 'Week-end ✨' : 'Semaine';
      pill.className='nuits-pill valid'; pill.style.display='flex';
      icon.textContent='✓'; txt.textContent=`3 nuits · Souffler ${lbl}`;
      bkState.isSpecial=false;
    } else if (diff===6) {
      bkState.dureeKey='semaine'; bkState.isSpecial=false;
      pill.className='nuits-pill valid'; pill.style.display='flex';
      icon.textContent='✓'; txt.textContent='6 nuits · Le Ressourcement 🌊';
    } else if (diff===10) {
      bkState.dureeKey='long'; bkState.isSpecial=false;
      pill.className='nuits-pill valid'; pill.style.display='flex';
      icon.textContent='✓'; txt.textContent='10 nuits · Vibre 🔥';
    } else if (diff===14) {
      bkState.dureeKey='long_plus'; bkState.isSpecial=false;
      pill.className='nuits-pill valid'; pill.style.display='flex';
      icon.textContent='✓'; txt.textContent='14 nuits · Vibre+ 🌟';
    } else {
      bkState.dureeKey=null; bkState.isSpecial=true;
      pill.className='nuits-pill special'; pill.style.display='flex';
      icon.textContent='✨'; txt.textContent=`${diff} nuits · Durée sur mesure`;
    }

    revealFlow();
    bkUpdateSteps();
  } catch (err) {
    console.error('Booking date error:', err);
  }
}

