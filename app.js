function renderStats() {
  const now = new Date();
  const monthStart = new Date(currentYear,currentMonth,1).toISOString().split('T')[0];
  const monthEnd = new Date(currentYear,currentMonth+1,0).toISOString().split('T')[0];

  const active = reservations.filter(r=>r.statut!=='blocked' && r.date_depart>=monthStart && r.date_arrive<=monthEnd);
  const nuits = active.reduce((s,r)=>{
    const start = Math.max(new Date(r.date_arrive),new Date(monthStart));
    const end = Math.min(new Date(r.date_depart),new Date(monthEnd));
    return s + Math.max(0,Math.round((end-start)/(864e5)));
  },0);
  const totalBedNights = 13 * new Date(currentYear,currentMonth+1,0).getDate();
  const taux = Math.round(nuits/totalBedNights*100);

  document.getElementById('stat-total').textContent = reservations.filter(r=>r.statut!=='blocked').length;
  document.getElementById('stat-active').textContent = active.length;
  document.getElementById('stat-taux').textContent = taux + '%';
  document.getElementById('stat-nuits').textContent = nuits;
  document.getElementById('stat-surf').textContent = reservations.filter(r=>r.package==='Surf').length;
  document.getElementById('stat-wellness').textContent = reservations.filter(r=>r.package==='Wellness').length;
  document.getElementById('stat-nomad').textContent = reservations.filter(r=>r.package==='Nomad').length;
  document.getElementById('stat-blocked').textContent = reservations.filter(r=>r.statut==='blocked').length;

  // Helper: render bar chart
  function renderBars(elId, data, colorFn) {
    const el = document.getElementById(elId);
    if (!el) return;
    const total = Object.values(data).reduce((s,v)=>s+v,0)||1;
    const sorted = Object.entries(data).sort((a,b)=>b[1]-a[1]).slice(0,6);
    el.innerHTML = sorted.length ? sorted.map(([k,v])=>`
      <div style="margin-bottom:0.55rem">
        <div style="display:flex;justify-content:space-between;font-size:0.78rem;margin-bottom:2px">
          <span>${k||'Non précisé'}</span><strong>${v} (${Math.round(v/total*100)}%)</strong>
        </div>
        <div style="background:var(--w2);border-radius:4px;height:8px;overflow:hidden">
          <div style="background:${colorFn(k)};height:100%;width:${Math.round(v/total*100)}%;border-radius:4px;transition:width 0.5s"></div>
        </div>
      </div>`).join('')
    : '<div style="color:var(--c2);font-size:0.82rem">Aucune donnée</div>';
  }

  const paysData = {}, langueData = {}, sexeData = {};
  reservations.filter(r=>r.statut!=='blocked').forEach(r=>{
    if(r.pays) paysData[r.pays] = (paysData[r.pays]||0)+1;
    if(r.langue) langueData[r.langue] = (langueData[r.langue]||0)+1;
    if(r.sexe) sexeData[r.sexe] = (sexeData[r.sexe]||0)+1;
  });

  const paysCols = {'France':'#0055A4','Belgique':'#000','Pays-Bas':'#FF6600','Royaume-Uni':'#CF142B','Allemagne':'#FFCC00','Espagne':'#AA151B'};
  renderBars('stat-pays', paysData, k => paysCols[k]||'var(--t1)');
  renderBars('stat-langues', langueData, () => 'var(--blue)');
  renderBars('stat-sexes', sexeData, k => k==='Femme'?'#E91E8C':k==='Homme'?'var(--blue)':'var(--c2)');
}

